# Run each named infrastructure test N times against the running stack, and tally passes and failures.
# Flaky timing shows up here, not in a single run (M2: the ledger race test passed once and failed in CI).
# Usage (from the repository root, stack running):
#   powershell -ExecutionPolicy Bypass -File scripts\repeat_tests.ps1 -Tests two_relays,crash_after_publish -Times 10 -Out docs\evidence\runs.md
# -Tests are pytest -k expressions, one test each. With -Out:
#   - the result table is saved there (a stored result file, standing rule 3)
#   - the full output of every run that didn't pass is saved next to it as <Out>.<test>.run<N>.log, so a failure
#     can be read later (the first version kept nothing, and one unexplained run couldn't be examined)
#   - lines a test prints that start with "evidence:" are collected under the table
# No value from .env is printed.
param(
    [Parameter(Mandatory = $true)][string[]]$Tests,
    [int]$Times = 10,
    [string]$Out = ""
)
$Tests = @($Tests | ForEach-Object { $_ -split "," } | ForEach-Object { $_.Trim() } | Where-Object { $_ })
$ErrorActionPreference = "Continue"
Set-Location (Split-Path -Parent $PSScriptRoot)
$utf8 = New-Object System.Text.UTF8Encoding $false
if ($Out) { New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Out) | Out-Null }
$rows = New-Object System.Collections.Generic.List[object]
$notes = New-Object System.Collections.Generic.List[string]
foreach ($test in $Tests) {
    $passed = 0; $failed = 0; $other = 0; $seconds = New-Object System.Collections.Generic.List[double]
    foreach ($i in 1..$Times) {
        $watch = [System.Diagnostics.Stopwatch]::StartNew()
        # No extra -q: pyproject already sets -q, and -qq drops the "1 passed" summary this script reads.
        # -s lets a test's "evidence:" lines through.
        $output = @(uv run python scripts\run_integration.py -k $test -s 2>&1 | ForEach-Object { "$_" })
        $watch.Stop(); $seconds.Add($watch.Elapsed.TotalSeconds)
        $summary = ($output | Select-String -Pattern "^\d+ (passed|failed)|^\d+ failed|, \d+ passed" | Select-Object -Last 1)
        $line = if ($summary) { $summary.Line } else { "" }
        foreach ($e in ($output | Select-String -Pattern "^evidence:")) { $notes.Add("``$test`` run ${i}: " + $e.Line.Substring(9).Trim()) }
        if ($line -match "^1 passed") { $passed++; continue }
        if ($line -match "failed") { $failed++; Write-Host "  run $i of '$test' FAILED: $line" }
        else { $other++; Write-Host "  run $i of '$test': no single-test summary" }
        if ($Out) {
            $log = "$Out.$($test -replace '[^\w]', '_').run$i.log"
            [System.IO.File]::WriteAllLines((Join-Path $PWD $log), $output, $utf8)
            Write-Host "  saved to $log"
        }
    }
    $rows.Add([pscustomobject]@{
        Test = $test; Runs = $Times; Passed = $passed; Failed = $failed; NotOneTest = $other
        MeanSeconds = [math]::Round((($seconds | Measure-Object -Average).Average), 1)
        MaxSeconds = [math]::Round((($seconds | Measure-Object -Maximum).Maximum), 1)
    })
}
Write-Host ($rows | Format-Table -AutoSize | Out-String -Width 200)
if ($Out) {
    $stamp = (Get-Date).ToUniversalTime().ToString("yyyy-MM-dd HH:mm") + " UTC"
    $commit = (git rev-parse --short HEAD)
    $md = @(
        "# Repeat runs", "",
        "Generated by ``scripts\repeat_tests.ps1`` on $stamp, at commit ``$commit`` plus the working tree.",
        "Each run is one ``pytest -k <test>`` against the local stack (``REQUIRE_MARKERS=postgres,kafka``).", "",
        "| Test | Runs | Passed | Failed | Not one test | Mean s | Max s |", "|---|---|---|---|---|---|---|"
    )
    foreach ($r in $rows) { $md += "| ``$($r.Test)`` | $($r.Runs) | $($r.Passed) | $($r.Failed) | $($r.NotOneTest) | $($r.MeanSeconds) | $($r.MaxSeconds) |" }
    if ($notes.Count -gt 0) { $md += ""; $md += "Measurements printed by the tests:"; $md += ""; foreach ($n in $notes) { $md += "- $n" } }
    [System.IO.File]::WriteAllLines((Join-Path $PWD $Out), $md, $utf8)
    Write-Host "Saved to $Out"
}
$bad = @($rows | Where-Object { $_.Passed -ne $_.Runs })
if ($bad.Count -gt 0) { exit 1 }
exit 0
